async function request(path, options = {}) {
  const response = await fetch(`${apiBase}${path}`, {
    ...options,
    headers: {
      "Content-Type": "application/json",
      ...options.headers,
    },
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(
      `${options.method || "GET"} ${path} failed: ${response.status} ${body}`,
    );
  }

  if (response.status === 204) {
    return null;
  }

  return response.json();
}

function toJobPayload(job) {
  const { events, ...payload } = job;
  return payload;
}

const existingJobs = await request("/jobs");
const existingKeys = new Set(
  existingJobs.map(
    (job) =>
      `${job.platform || ""}::${job.company_name || ""}::${job.job_title || ""}`,
  ),
);

let created = 0;
let skipped = 0;

for (const job of jobs) {
  const key = `${job.platform || ""}::${job.company_name || ""}::${job.job_title || ""}`;
  if (existingKeys.has(key)) {
    skipped += 1;
    continue;
  }

  const createdJob = await request("/jobs", {
    method: "POST",
    body: JSON.stringify(toJobPayload(job)),
  });
  created += 1;

  for (const eventType of job.events || []) {
    await request(`/jobs/${createdJob.id}/events`, {
      method: "POST",
      body: JSON.stringify({
        event_type: eventType,
        notes: `${seedTag} 演示事件：${eventType}`,
      }),
    });
  }
}

